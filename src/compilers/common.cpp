std::string pascal(const std::string& name) {
  std::string out;
  std::size_t start = 0;
  while (true) {
    std::size_t pos = name.find('_', start);
    std::string part = name.substr(start, pos == std::string::npos ? std::string::npos : pos - start);
    if (!part.empty()) out += py::upper(part.substr(0, 1)) + part.substr(1);
    if (pos == std::string::npos) break;
    start = pos + 1;
  }
  return out;
}

std::string header(const Behavior& b, const std::string& comment) {
  std::vector<std::string> techs;
  for (const auto& t : b.atlas.techniques) techs.push_back(t.id + "(" + t.relationship + ")");
  const std::string src = b.source_path ? b.source_path->filename().string() : b.id;
  return py::join(
      {
          comment + " " + b.id + " | " + b.name,
          comment + " ATLAS tactics: " + py::join(b.atlas.tactics, ", ") + " | techniques: " + py::join(techs, ", "),
          comment + " severity=" + to_string(b.severity) + " confidence=" + to_string(b.confidence) +
              " status=" + to_string(b.status),
          comment + " GENERATED by atlas-behavior-map from " + src + ". Do not edit.",
      },
      "\n");
}

const std::vector<Target>& targets() {
  static const std::vector<Target> t = {
      {"kql", kql::compile_behavior, ".kql"},
      {"sigma", sigma::compile_behavior, ".yml"},
      {"spl", spl::compile_behavior, ".spl"},
  };
  return t;
}

const Target* find_target(const std::string& name) {
  for (const auto& t : targets())
    if (t.name == name) return &t;
  return nullptr;
}

